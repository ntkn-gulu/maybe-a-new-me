export function translate(language: Language, key: StringKey, params?: StringParams): string
{
    let text = STRINGS[language][key];
    if (params)
    {
        for (const [name, value] of Object.entries(params))
        {
            text = text.replaceAll(`{${name}}`, String(value));
        }
    }
    return text;
}

